CREATE PROCEDURE [dbo].[MergeEtfDailyHoldings]
AS
INSERT INTO dbo.EtfDailyHoldings
(FundHoldingsAsOfDate,
 FundTicker,
 Name,
 Sector,
 AssetClass,
 MarketValue,
 Weight,
 NotionalValue,
 ParValue,
 CUSIP,
 ISIN,
 SEDOL,
 Location,
 Exchange,
 Currency,
 Duration,
 YTM,
 FXRate,
 Maturity,
 Coupon,
 ModDuration,
 YieldtoCall,
 YieldtoWorst,
 RealDuration,
 RealYTM,
 MarketCurrency,
 AccrualDate,
 EffectiveDate,
 Ticker,
 Shares,
 Price,
 Type)
       SELECT edhs.FundHoldingsAsOfDate,
              edhs.FundTicker,
              edhs.Name,
              edhs.Sector,
              edhs.AssetClass,
              edhs.MarketValue,
              edhs.Weight,
              edhs.NotionalValue,
              edhs.ParValue,
              edhs.CUSIP,
              edhs.ISIN,
              edhs.SEDOL,
              edhs.Location,
              edhs.Exchange,
              edhs.Currency,
              edhs.Duration,
              edhs.YTM,
              edhs.FXRate,
              edhs.Maturity,
              edhs.Coupon,
              edhs.ModDuration,
              edhs.YieldtoCall,
              edhs.YieldtoWorst,
              edhs.RealDuration,
              edhs.RealYTM,
              edhs.MarketCurrency,
              edhs.AccrualDate,
              edhs.EffectiveDate,
              edhs.Ticker,
              edhs.Shares,
              edhs.Price,
              edhs.Type
       FROM dbo.EtfDailyHoldingsStaging edhs
GO